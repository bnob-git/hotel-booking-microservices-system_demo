-- One row per processed booking event; the unique event_id makes consumption idempotent.
CREATE TABLE notification_log (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id          UUID          NOT NULL,
    booking_id        BIGINT,
    confirmation_code VARCHAR(32),
    event_type        VARCHAR(50)   NOT NULL,
    recipient         VARCHAR(255),
    subject           VARCHAR(255),
    status            VARCHAR(20)   NOT NULL,
    error             VARCHAR(1000),
    sent_at           TIMESTAMP     NOT NULL,
    CONSTRAINT uk_notification_log_event_id UNIQUE (event_id)
);

CREATE INDEX idx_notification_log_booking ON notification_log (booking_id);
CREATE INDEX idx_notification_log_sent_at ON notification_log (sent_at);
