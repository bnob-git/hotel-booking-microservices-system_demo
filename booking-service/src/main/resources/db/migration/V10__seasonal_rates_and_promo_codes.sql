-- Track A: seasonal pricing rules and promo codes (reference data, seeded here so tests/E2E can rely on it).
-- Month-day bounds are 'MM-DD' strings; a window whose start is after its end wraps over the new year.
CREATE TABLE seasonal_rates (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code            VARCHAR(32)   NOT NULL,
    name            VARCHAR(100)  NOT NULL,
    start_month_day VARCHAR(5)    NOT NULL,
    end_month_day   VARCHAR(5)    NOT NULL,
    multiplier      NUMERIC(6, 4) NOT NULL,
    active          BOOLEAN       DEFAULT TRUE NOT NULL,
    CONSTRAINT uk_seasonal_rates_code UNIQUE (code)
);

