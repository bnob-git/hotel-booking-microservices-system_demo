CREATE TABLE loyalty_accounts (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id         BIGINT       NOT NULL,
    username        VARCHAR(255),
    points_balance  BIGINT       NOT NULL DEFAULT 0,
    lifetime_points BIGINT       NOT NULL DEFAULT 0,
    tier            VARCHAR(20)  NOT NULL DEFAULT 'BRONZE',
    created_at      TIMESTAMP    NOT NULL,
    updated_at      TIMESTAMP    NOT NULL,
    CONSTRAINT uk_loyalty_accounts_user UNIQUE (user_id)
);

CREATE TABLE points_transactions (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id           BIGINT        NOT NULL,
    type              VARCHAR(20)   NOT NULL,
    points            BIGINT        NOT NULL,
    booking_id        BIGINT,
    confirmation_code VARCHAR(20),
    description       VARCHAR(500),
    source_event_id   UUID,
    created_at        TIMESTAMP     NOT NULL,
    CONSTRAINT uk_points_transactions_source_event UNIQUE (source_event_id)
);

CREATE INDEX idx_points_transactions_user ON points_transactions (user_id, created_at);
CREATE INDEX idx_points_transactions_booking ON points_transactions (booking_id, type);

CREATE TABLE redemptions (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id           BIGINT         NOT NULL,
    points            BIGINT         NOT NULL,
    discount_amount   NUMERIC(10, 2) NOT NULL,
    booking_reference VARCHAR(100),
    status            VARCHAR(20)    NOT NULL,
    created_at        TIMESTAMP      NOT NULL,
    reversed_at       TIMESTAMP
);

CREATE INDEX idx_redemptions_user ON redemptions (user_id);
